ROOT = Path(__file__).resolve().parent.parent
GRAFANA = ROOT / "infra" / "grafana"
FILES = sorted((GRAFANA / "dashboards").glob("*.json"))
DATASOURCE = {"type": "prometheus", "uid": "simex-prometheus"}
IDENTIFIER = r"[a-zA-Z_:][a-zA-Z0-9_:]*"


def metric_selectors(expression):
    """Extract named selectors from our queries, not names inside labels/grouping/functions.

    This is a selector guard, not a PromQL parser: CI also feeds every expression to promtool.
    Indirect selectors are prohibited so a query cannot evade the collector-name check.
    """
    expression = re.sub(r'"(?:\\.|[^"\\])*"', '""', expression)
    assert "__name__" not in expression, "use a literal metric name"
    for match in re.finditer(r"\{", expression):
        assert re.search(IDENTIFIER + r"\s*$", expression[: match.start()]), (
            "use a named metric selector"
        )
    expression = re.sub(r"\{[^{}]*\}", "", expression)
    expression = re.sub(r"\[[^\[\]]*\]", "", expression)
    expression = re.sub(
        r"\b(?:by|without|on|ignoring|group_left|group_right)\s*\([^)]*\)", "", expression
    )
    expression = re.sub(IDENTIFIER + r"\s*(?=\()", "", expression)
    return set(re.findall(IDENTIFIER, expression)) - {"and", "or", "unless", "bool"}


@pytest.fixture(scope="module")
def exported_metrics():
    registry = CollectorRegistry()
    for kind in (IngestMetrics, BookMetrics, RunnerMetrics, LedgerMetrics, RecorderMetrics):
        kind(registry=registry)
    names = {"up"}  # Generated by Prometheus scrapes, not by a SimEx collector.
    for family in registry.collect():
        suffixes = {
            "counter": ("_total", "_created"),
            "histogram": ("_bucket", "_sum", "_count", "_created"),
            "gauge": ("",),
        }[family.type]
        names.update(family.name + suffix for suffix in suffixes)
    return names


def panels(dashboard):
    for panel in dashboard["panels"]:
        yield panel
        if "panels" in panel:
            yield from panels(panel)


def assert_known_metrics(expression, exported):
    selectors = metric_selectors(expression)
    assert selectors, "query must reference a named metric"
    assert not selectors - exported, f"unknown metric selectors: {sorted(selectors - exported)}"


def test_all_four_dashboards_are_present_with_stable_unique_ids():
    assert {path.stem for path in FILES} == {"feed", "exchange", "ledger", "recorder"}
    dashboards = [json.loads(path.read_text()) for path in FILES]
    assert len({dashboard["uid"] for dashboard in dashboards}) == 4
    for path, dashboard in zip(FILES, dashboards, strict=True):
        assert dashboard["uid"] == "simex-" + path.stem
        assert dashboard["editable"] is False
        assert dashboard["timezone"] == "utc"
        assert dashboard["refresh"] == "30s"
        assert dashboard["panels"]
        ids = [panel["id"] for panel in panels(dashboard)]
        assert len(ids) == len(set(ids))
        assert {link["url"] for link in dashboard["links"]} == {
            "/d/" + other["uid"] for other in dashboards
        }


@pytest.mark.parametrize("path", FILES, ids=lambda path: path.stem)
def test_dashboard_queries_use_only_exported_system_metrics(path, exported_metrics):
    for panel in panels(json.loads(path.read_text())):
        if panel["type"] == "text":
            assert panel["options"]["mode"] == "markdown"
            assert panel["options"]["content"]
            continue
        assert panel["datasource"] == DATASOURCE
        assert panel["targets"], panel["title"]
        for target in panel["targets"]:
            assert target["datasource"] == DATASOURCE
            assert_known_metrics(target["expr"], exported_metrics)
            # System metrics only: no monetary market/account series in a shareable panel.
            for name in metric_selectors(target["expr"]):
                assert not re.search(
                    r"price|equity|pnl|profit|sharpe|drawdown|position|notional|balance", name
                ), name


