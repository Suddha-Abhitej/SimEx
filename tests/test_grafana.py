def test_selector_extraction_handles_labels_groups_and_histograms():
    expression = (
        "histogram_quantile(0.99, sum by (le, phase) (rate("
        'simex_ledger_latency_seconds_bucket{phase="simex_not_a_metric"}[$__rate_interval]))) '
        "or on() simex_ledger_halts_total"
    )
    assert metric_selectors(expression) == {
        "simex_ledger_latency_seconds_bucket",
        "simex_ledger_halts_total",
    }


def alert_expressions():
    """Read the existing rules' names/expressions without a YAML dependency.

    These are only the repository's simple alert blocks (scalar or folded expr). promtool
    validates the complete YAML and rules in CI; comments containing 'alert' are not rules.
    """
    for path in sorted((ROOT / "infra" / "prometheus" / "rules").glob("*.yml")):
        content = path.read_text()
        matches = list(re.finditer(r"(?m)^      - alert: (\w+)\s*$", content))
        for index, match in enumerate(matches):
            end = matches[index + 1].start() if index + 1 < len(matches) else len(content)
            block = content[match.end() : end]
            expression = re.search(r"(?m)^        expr: (.+)$", block)
            assert expression is not None, match[1]
            value = expression[1]
            if value in (">", ">-", "|", "|-"):
                lines = []
                for line in block[expression.end() :].splitlines():
                    if not line.strip():
                        continue
                    if not line.startswith("          "):
                        break
                    lines.append(line.strip())
                value = " ".join(lines)
            yield match[1], value


def test_every_prometheus_alert_has_a_panel_with_its_underlying_metrics():
    all_panels = [panel for path in FILES for panel in panels(json.loads(path.read_text()))]
    alerts = dict(alert_expressions())
    assert alerts  # An empty inventory must not make coverage pass vacuously.
    for name, expression in alerts.items():
        supporting = [panel for panel in all_panels if name in panel.get("description", "")]
        assert supporting, f"no panel for Prometheus alert {name}"
        displayed = {
            metric
            for panel in supporting
            for target in panel.get("targets", [])
            for metric in metric_selectors(target["expr"])
        }
        assert metric_selectors(expression) <= displayed, name


def test_no_grafana_alerting_definitions_are_provisioned():
    def keys(value):
        if isinstance(value, dict):
            for key, child in value.items():
                yield key
                yield from keys(child)
        elif isinstance(value, list):
            for child in value:
                yield from keys(child)

    assert not (GRAFANA / "provisioning" / "alerting").exists()
    for path in FILES:
        assert not {"alert", "alerting", "alertRule", "alertRules"} & set(
            keys(json.loads(path.read_text()))
        )


def test_provisioning_paths_datasource_and_readonly_compose_mounts_agree():
    # JSON is a YAML subset: .yml provisioning stays parseable without a new test dependency.
    sources = json.loads((GRAFANA / "provisioning/datasources/prometheus.yml").read_text())
    provider = json.loads((GRAFANA / "provisioning/dashboards/dashboards.yml").read_text())
    assert sources["apiVersion"] == provider["apiVersion"] == 1
    [source] = sources["datasources"]
    assert {key: source[key] for key in ("type", "uid")} == DATASOURCE
    assert source["url"] == "http://prometheus:9090"
    assert source["access"] == "proxy"
    assert source["isDefault"] is True
    assert source["editable"] is False
    assert source["jsonData"]["timeInterval"] == "15s"
    [provider] = provider["providers"]
    assert provider["type"] == "file"
    assert provider["allowUiUpdates"] is False
    assert provider["disableDeletion"] is False
    assert provider["options"]["path"] == "/var/lib/grafana/dashboards"
    compose = (ROOT / "compose.yaml").read_text().split("  grafana:\n", 1)[1]
    compose = compose.split("\nvolumes:", 1)[0]
    for local, remote in (
        ("provisioning/datasources", "/etc/grafana/provisioning/datasources"),
        ("provisioning/dashboards", "/etc/grafana/provisioning/dashboards"),
        ("dashboards", provider["options"]["path"]),
    ):
        assert (GRAFANA / local).is_dir()
        assert f"./infra/grafana/{local}:{remote}:ro" in compose
    assert 'profiles: ["monitoring"]' in compose
    assert '"127.0.0.1:${GRAFANA_PORT:-3000}:3000"' in compose
    assert "memory: 256M" in compose
    assert "grafana-data:/var/lib/grafana" in compose


def test_missing_measurements_and_coverage_are_explicit_and_link_the_followup():
    exchange = json.loads((GRAFANA / "dashboards/exchange.json").read_text())
    caveats = " ".join(
        panel["options"]["content"] for panel in exchange["panels"] if panel["type"] == "text"
    )
    assert "https://github.com/Suddha-Abhitej/SimEx/issues/111" in caveats
    for phrase in (
        "Submitted and accepted orders: not instrumented",
        "Tick-to-fill latency: not instrumented",
        "denominator",
        "early request-validation refusals",
        "eviction",
    ):
        assert phrase in caveats
    feed = (GRAFANA / "dashboards/feed.json").read_text()
    recorder = (GRAFANA / "dashboards/recorder.json").read_text()
    assert "unread-offset counts exist for the recorder only" in feed
    assert "persistent negative lag" in feed
    assert "Publication age can approach an hour" in recorder
